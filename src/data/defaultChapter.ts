/**
 * Intelligent parser to detect paragraphs, speaker roles, and character genders
 * Supports Mushoku Tensei character heuristics AND any generic novel/story dialogue!
 */
export function parseTextIntoParagraphs(rawText: string): ParagraphItem[] {
  const blocks = rawText
    .split(/\n+/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0);

  let lastSpeaker: SpeakerType = 'narrator';
  let lastGender: GenderType = 'neutral';
  let dialogueCount = 0;

  return blocks.map((text, idx) => {
    let speaker: SpeakerType = 'narrator';
    let speakerGender: GenderType = 'neutral';
    let speakerLabel = 'Narração';

    // Check if paragraph starts with a dialogue dash or quotation mark
    const isDialogue =
      text.startsWith('—') ||
      text.startsWith('-') ||
      text.startsWith('–') ||
      text.startsWith('"') ||
      text.startsWith('“');

    if (!isDialogue) {
      speaker = 'narrator';
      speakerGender = 'neutral';
      speakerLabel = 'Narração / Reflexão';
      lastSpeaker = 'narrator';
    } else {
      dialogueCount++;
      const lower = text.toLowerCase();

      // Explicit female markers (in Portuguese)
      const isFemaleExplicit =
        lower.includes('disse ela') ||
        lower.includes('respondeu ela') ||
        lower.includes('perguntou ela') ||
        lower.includes('gritou ela') ||
        lower.includes('sussurrou ela') ||
        lower.includes('disse a garota') ||
        lower.includes('disse a mulher') ||
        lower.includes('a jovem aprendiz') ||
        lower.includes('sylphie') ||
        lower.includes('eris') ||
        lower.includes('ariel') ||
        lower.includes('roxy') ||
        lower.includes('nanahoshi') ||
        lower.includes('tristina');

      // Explicit first-person speech markers
      const isFirstPerson =
        lower.includes('— eu disse') ||
        lower.includes('eu disse') ||
        lower.includes('perguntei') ||
        lower.includes('resmunguei') ||
        lower.includes('fiquei boquiaberto') ||
        lower.includes('continuei') ||
        lower.includes('respondi') ||
        lower.includes('exclamei') ||
        lower.includes('sussurrei') ||
        lower.includes('pensei');

      // Explicit deep male character / Orsted markers
      const isMaleDeep =
        lower.includes('disse orsted') ||
        lower.includes('assegurou orsted') ||
        lower.includes('orsted') ||
        lower.includes('disse ele') ||
        lower.includes('continuou ele') ||
        lower.includes('respondeu ele') ||
        lower.includes('afirmou ele') ||
        lower.includes('disse o homem') ||
        lower.includes('disse o velho') ||
        lower.includes('o mestre') ||
        lower.includes('o taberneiro');

      if (isFemaleExplicit) {
        speaker = 'female';
        speakerGender = 'female';
        speakerLabel = 'Voz Feminina';
        lastSpeaker = 'female';
        lastGender = 'female';
      } else if (isFirstPerson) {
        speaker = 'rudeus';
        speakerGender = 'male';
        speakerLabel = 'Rudeus (Voz Masculina Jovem)';
        lastSpeaker = 'rudeus';
        lastGender = 'male';
      } else if (isMaleDeep) {
        speaker = 'orsted';
        speakerGender = 'male';
        speakerLabel = 'Orsted (Voz Masculina Grave)';
        lastSpeaker = 'orsted';
        lastGender = 'male';
      } else {
        // Natural alternating conversation heuristic:
        // Dialogue 1 -> Masculino Grave / Interlocutor (Orsted)
        // Dialogue 2 -> Masculino Jovem / Protagonista (Rudeus)
        // Dialogue between man and woman alternate accordingly
        if (lastSpeaker === 'rudeus') {
          speaker = 'orsted';
          speakerGender = 'male';
          speakerLabel = 'Personagem (Masculino Grave)';
          lastSpeaker = 'orsted';
          lastGender = 'male';
        } else if (lastSpeaker === 'orsted') {
          speaker = 'rudeus';
          speakerGender = 'male';
          speakerLabel = 'Personagem (Masculino Ágil)';
          lastSpeaker = 'rudeus';
          lastGender = 'male';
        } else if (lastSpeaker === 'female') {
          speaker = 'orsted';
          speakerGender = 'male';
          speakerLabel = 'Personagem (Masculino)';
          lastSpeaker = 'orsted';
          lastGender = 'male';
        } else {
          // If starting dialogue
          if (dialogueCount % 2 === 1) {
            speaker = 'orsted';
            speakerGender = 'male';
            speakerLabel = 'Personagem 1 (Masculino)';
            lastSpeaker = 'orsted';
            lastGender = 'male';
          } else {
            speaker = 'rudeus';
            speakerGender = 'male';
            speakerLabel = 'Personagem 2 (Masculino)';
            lastSpeaker = 'rudeus';
            lastGender = 'male';
          }
        }
      }
    }

    return {
      id: idx,
      text,
      speaker,
      speakerGender,
      speakerLabel,
    };
  });
}
